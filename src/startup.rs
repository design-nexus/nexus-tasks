    #[test]
    fn merges_units() {
        let units = r#"[{"unit":"a.service","load":"loaded","active":"active","sub":"running","description":"A"}]"#;
        let files = r#"[{"unit_file":"a.service","state":"enabled"},{"unit_file":"b.service","state":"disabled"},{"unit_file":"t@.service","state":"static"}]"#;
        let u = parse_units(units, files);
        assert_eq!(u.len(), 2);
        assert!(u[0].running());
        assert_eq!(u[0].file_state, "enabled");
        assert_eq!(u[1].active, "inactive");
    }
